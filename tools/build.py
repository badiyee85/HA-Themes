#!/usr/bin/env python3
"""Build desktop/plugin.js (the installable theme pack) from themes/<name>/.

Each themes/<name>/ holds theme.json (a DesktopTheme minus customCSS; its
"name" must equal the folder) and, optionally, theme.css (that theme's
customCSS, scoped to :root[data-hermes-theme='<name>']). The output is plain
data plus one THEMES_AREA registration per theme — the shape the Desktop
Plugin SDK documents for theme contributions: no DOM access, no <style> of its
own, no other imports.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN_ID = "ha-themes"
CSS_CAP = 32768  # same budget the skin engine allows customCSS; keep each theme under it


def minify(css: str) -> str:
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = re.sub(r"\s+", " ", css)
    css = re.sub(r"\s*([{};,>])\s*", r"\1", css)
    css = css.replace(";}", "}")
    return css.strip()


def theme_dirs() -> list[Path]:
    return sorted(p for p in (ROOT / "themes").iterdir() if (p / "theme.json").is_file())


def theme_data(folder: Path) -> dict:
    theme = json.loads((folder / "theme.json").read_text(encoding="utf-8"))
    if theme.get("name") != folder.name:
        raise SystemExit(f"{folder}: theme.json name {theme.get('name')!r} must equal the folder name")
    # One palette for both modes: these looks do not invert with the light/dark
    # toggle (the app still paints from the background luminance).
    theme["darkColors"] = dict(theme["colors"])
    css_file = folder / "theme.css"
    if css_file.is_file():
        theme["customCSS"] = minify(css_file.read_text(encoding="utf-8"))
    return theme


def all_themes() -> list[dict]:
    return [theme_data(d) for d in theme_dirs()]


def version() -> str:
    m = re.search(r"^version:\s*[\"']?([0-9][^\s\"']*)", (ROOT / "plugin.yaml").read_text(encoding="utf-8"), re.M)
    if not m:
        raise SystemExit("plugin.yaml has no version")
    return m.group(1)


def render(themes: list[dict]) -> str:
    body = json.dumps(themes, indent=2, ensure_ascii=False)
    names = ", ".join(t["name"] for t in themes)
    return f"""// HA Themes for Hermes Desktop — v{version()} ({names})
// GENERATED by tools/build.py from themes/<name>/theme.json (+ theme.css). Edit those, not this file.
// A theme-only Desktop plugin: it registers each DesktopTheme through the SDK's THEMES_AREA.
// Registering lists the themes in Settings -> Appearance (and `/skin <name>` in a Desktop chat);
// it never selects one. The app injects a theme's customCSS only while that theme is active.
import {{ THEMES_AREA }} from '@hermes/plugin-sdk'

const THEMES = {body}

export default {{
  id: '{PLUGIN_ID}',
  name: 'HA Themes',
  register(ctx) {{
    ctx.registerMany(THEMES.map(theme => ({{ id: theme.name, area: THEMES_AREA, data: theme }})))
  }}
}}
"""


def main() -> int:
    themes = all_themes()
    for t in themes:
        size = len(t.get("customCSS", "").encode("utf-8"))
        if size > CSS_CAP:
            print(f"{t['name']}: customCSS is {size} bytes; keep it under {CSS_CAP}", file=sys.stderr)
            return 1
    out = ROOT / "desktop" / "plugin.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text(render(themes), encoding="utf-8")
    summary = ", ".join(f"{t['name']} ({len(t.get('customCSS', ''))} B css)" for t in themes)
    print(f"wrote {out.relative_to(ROOT)}: {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
